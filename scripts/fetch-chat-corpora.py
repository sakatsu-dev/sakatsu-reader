"""Acquire the two CC BY-SA Japanese chat corpora at pinned revisions, and record their terms.

    python scripts/fetch-chat-corpora.py --dossier      # terms only, no bulk data
    python scripts/fetch-chat-corpora.py --download     # pinned archives, then normalize

Bulk data and the normalized corpus go under ignored `scratch/`. Only this script, its tests and
the dossier are tracked.

# What is taken, and what is deliberately left

Both repositories carry more than the dialogue text, and two parts are excluded on purpose:

- **`interlocutors.json`** — the participants' persona and personality profiles, including Big Five
  and social-skill inventories about real people. The pilot is about colloquial forms and has no use
  for them, so they are never downloaded into the working corpus.
- **`llm_dialogue_system/`** in RealPersonaChat — dialogues *generated by GPT-4 and GPT-3.5*. They
  sit beside the human corpus in the same repository, and a naive "take every JSON" would mix
  machine-written Japanese into a corpus whose entire purpose is evidence about how people write.

`evaluations` (subjective ratings) and RealPersonaChat's per-utterance `timestamp` are also dropped:
neither is needed for source order, speaker grouping or condition, and importing data you have no
use for is not free.

# Incomplete downloads

An archive is written to a `.part` file, hashed, and only then renamed. A partial or mismatched
download therefore cannot be mistaken for a complete one on the next run — the `.part` is not a
corpus, and `--download` re-fetches rather than resuming into a file whose contents it cannot
vouch for.
"""

