#: Files whose text is recorded verbatim in the dossier, so the terms travel with the data.
TERMS_FILES = ("LICENSE", "README.md", "VERSION")


def fetch(url, timeout=60):
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=timeout) as response:
        return response.read()


def digest(data):
    return hashlib.sha256(data).hexdigest()


def dossier(sources=SOURCES, pause=1.0):
    """Licence, usage notes and attribution for each source, with the bytes hashed.

    Fetched at the **pinned** revision, so what is recorded is what the data was published under —
    not whatever the repository says later.
    """
    record = {"generated": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "sources": {}}
    for name, source in sources.items():
        entry = {
            "repository": f"https://github.com/{source['repo']}",
            "revision": source["revision"],
            "licence": source["licence"],
            "licence_url": source["licence_url"],
            "citation": source["citation"],
            "funding": source["funding"],
            "excluded_from_acquisition": source["excluded"],
            "terms": {},
        }
        for path in TERMS_FILES:
            url = f"https://raw.githubusercontent.com/{source['repo']}/{source['revision']}/{path}"
            body = fetch(url)
            entry["terms"][path] = {
                "url": url,
                "bytes": len(body),
                "sha256": digest(body),
                "text": body.decode("utf-8") if path == "VERSION" else None,
            }
            time.sleep(pause)
        record["sources"][name] = entry
    record["export_policy"] = (
        "Both corpora are CC BY-SA 4.0 with no additional usage terms beyond the licence — the "
        "repositories' own licence sections state only CC BY-SA 4.0. Any open export of normalized "
        "text or annotations derived from them is published under CC BY-SA 4.0, preserving the "
        "notices above, naming the citation, and identifying that it has been modified. This is an "
        "export policy, not a claim that every transformation is legally an adaptation, and it does "
        "not settle how a trained model would be licensed; training and model distribution are out "
        "of scope for this pilot. Capture text and images are private and never enter an open "
        "export."
    )
    return record


def archive_url(source):
    return f"https://codeload.github.com/{source['repo']}/tar.gz/{source['revision']}"


def download_archive(source, into, force=False):
    """The pinned archive, written through a `.part` file so a partial one is never promoted.

    Returns `(path, sha256, bytes, reused)`.
    """
    into.mkdir(parents=True, exist_ok=True)
    final = into / f"{source['revision']}.tar.gz"
    if final.exists() and not force:
        body = final.read_bytes()
        return final, digest(body), len(body), True

    partial = final.with_suffix(".part")
    body = fetch(archive_url(source), timeout=300)
    if not body:
        raise RuntimeError(f"empty archive from {archive_url(source)}")
    partial.write_bytes(body)
    # Only now is it a complete archive. Until the rename, nothing can mistake it for one.
    partial.replace(final)
    return final, digest(body), len(body), False


def wanted(source, name):
    """Whether an archive member is dialogue data this pilot should read.

    The archive's top directory is `<repo>-<revision>/`, which is stripped before matching so the
    paths here are the repository's own.
    """
    _, _, relative = name.partition("/")
    if not relative.endswith(".json"):
        return False
    for excluded in source["excluded"]:
        if relative == excluded or relative.startswith(excluded):
            return False
    return relative.startswith(source["dialogues"])


def normalize_dialogue(source_name, relative, payload):
    """One dialogue as the pilot needs it, and nothing more.

    Keeps the dialogue and utterance identity, source order, the pseudonymous speaker, the text
    unchanged, and the condition where the corpus supplies one. Drops `evaluations` (subjective
    ratings) and RealPersonaChat's per-utterance `timestamp`.
    """
    utterances = []
    for index, utterance in enumerate(payload.get("utterances", [])):
        text = utterance.get("text", "")
        utterances.append(
            {
                "utterance_id": str(utterance.get("utterance_id", index)),
                "order": index,
                "speaker": utterance.get("interlocutor_id"),
                "text": text,
                "sha256": digest(text.encode("utf-8")),
            }
        )
    return {
        "source": source_name,
        "path": relative,
        "dialogue_id": str(payload.get("dialogue_id")),
        "condition": payload.get("dialogue_type"),
        "speakers": list(payload.get("interlocutors", [])),
        "utterances": utterances,
    }


def extract(source_name, source, archive, out):
    """Normalize the wanted members of `archive` into a JSONL, returning a summary."""
    dialogues = 0
    utterances = 0
    skipped = 0
    out.parent.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive, "r:gz") as tar, out.open("w", encoding="utf-8") as handle:
        for member in tar:
            if not member.isfile():
                continue
            if not wanted(source, member.name):
                skipped += 1
                continue
            extracted = tar.extractfile(member)
            if extracted is None:
                skipped += 1
                continue
            payload = json.loads(extracted.read().decode("utf-8"))
            _, _, relative = member.name.partition("/")
            record = normalize_dialogue(source_name, relative, payload)
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")
            dialogues += 1
            utterances += len(record["utterances"])
    return {"dialogues": dialogues, "utterances": utterances, "members_skipped": skipped}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dossier", action="store_true", help="write the licence dossier only")
    parser.add_argument("--download", action="store_true", help="fetch the pinned archives")
    parser.add_argument("--force", action="store_true", help="re-fetch even if the archive is here")
    parser.add_argument("--out", default=str(ROOT / "scratch" / "colloquial" / "chat"))
    args = parser.parse_args(argv)
    if not (args.dossier or args.download):
        parser.error("choose --dossier, --download, or both")

    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    if args.dossier:
        record = dossier()
        path = out / "licence-dossier.json"
        path.write_text(json.dumps(record, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"wrote {path}")
        for name, entry in record["sources"].items():
            print(f"  {name:34} {entry['licence']}  @ {entry['revision'][:12]}")

    if args.download:
        manifest = {"acquired": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "sources": {}}
        for name, source in SOURCES.items():
            archive, archive_sha, size, reused = download_archive(
                source, out / "archives", force=args.force
            )
            summary = extract(name, source, archive, out / f"{name}.jsonl")
            manifest["sources"][name] = {
                "repository": f"https://github.com/{source['repo']}",
                "revision": source["revision"],
                "archive_url": archive_url(source),
                "archive_sha256": archive_sha,
                "archive_bytes": size,
                "archive_reused": reused,
                **summary,
            }
            print(
                f"  {name:34} {summary['dialogues']:>6} dialogues"
                f" {summary['utterances']:>8} utterances"
                f"  ({'cached' if reused else 'downloaded'})"
            )
        path = out / "acquisition-manifest.json"
        path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
